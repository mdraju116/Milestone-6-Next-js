/* 
✅✅✅Hydration in Next.js
Hydration is the process where React takes the HTML already generated by the server and
makes it interactive in the browser.

➡️Simple idea
Suppose Next.js sends this HTML:
<button>Count: 0</button>

The user can see the button, but React needs to connect JavaScript to it so that clicking the button
can change the count.
That's hydration.

➡️Flow
Server
  ↓
Generates HTML
  ↓
Browser receives HTML
  ↓
User can see UI
  ↓
React loads JavaScript
  ↓
Hydration
  ↓
UI becomes interactive


➡️Example
"use client";
import { useState } from "react";

export default function Counter() {
  const [count, setCount] = useState(0);

  return (
    <button onClick={() => setCount(count + 1)}>
      Count: {count}
    </button>
  );
}


➡️➡️What happens?

1. Server generates the initial HTML:
    <button>Count: 0</button>

2. Browser displays it.

3. React JavaScript loads.

4. React hydrates the button.

    Now React knows:
    onClick → increase count

5. User clicks:

        Count: 0
          ↓ click
        Count: 1
          ↓ click
        Count: 2


✅✅Rendering vs Hydration

| Rendering                  | Hydration                          |
| -------------------------- | ---------------------------------- |
| Generates the UI/HTML      | Makes existing UI interactive      |
| Can happen on server       | Happens in browser                 |
| Produces HTML              | Connects React logic/events        |
| Happens before interaction | Happens after HTML reaches browser |




🧠 Easy memory
Rendering = Create the UI
Hydration = Make the UI interactive

Or:
Rendering → "Show it"
Hydration → "Make it work"






*/